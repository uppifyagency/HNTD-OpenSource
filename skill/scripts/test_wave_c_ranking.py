# ── #17 JD-04: gate exclusion filter ─────────────────────────────────────────

class TestGateExclusion:
    def _write_gate(self, tmp_path, scorable, eliminated):
        (tmp_path / "score-gate-T.json").write_text(json.dumps(
            {"scorable": scorable, "eliminated": eliminated}))

    def test_eliminated_devs_filtered(self, tmp_path):
        self._write_gate(tmp_path, [{"login": "a"}, {"login": "c"}], [{"login": "b"}])
        pf = {"a": {}, "b": {}, "c": {}}
        assert set(apply_gate_filter(pf, "T", tmp_path)) == {"a", "c"}

    def test_stale_pass1_gate_keeps_pass2_devs(self, tmp_path):
        """Adversarial-review F1: the gate file is NOT regenerated by the pass2
        loop — a pass2 survivor is unknown to it and MUST pass through.
        Intersection with `scorable` silently dropped every pass2 dev."""
        self._write_gate(tmp_path, [{"login": "a"}], [{"login": "b"}])
        pf = {"a": {}, "b": {}, "pass2new": {}}
        assert set(apply_gate_filter(pf, "T", tmp_path)) == {"a", "pass2new"}

    def test_missing_gate_file_keeps_all(self, tmp_path):
        pf = {"a": {}, "b": {}}
        assert apply_gate_filter(pf, "T", tmp_path) == pf

    def test_corrupt_gate_file_keeps_all(self, tmp_path):
        (tmp_path / "score-gate-T.json").write_text("{nope")
        pf = {"a": {}}
        assert apply_gate_filter(pf, "T", tmp_path) == pf

    def test_empty_eliminated_keeps_all(self, tmp_path):
        self._write_gate(tmp_path, [{"login": "a"}], [])
        pf = {"a": {}, "b": {}}
        assert apply_gate_filter(pf, "T", tmp_path) == pf


# ── #18 QT-02: singleton-free chunking ───────────────────────────────────────

class TestChunkWithoutSingletons:
    def test_exact_multiple_unchanged(self):
        chunks = chunk_without_singletons(list(range(16)))
        assert [len(c) for c in chunks] == [8, 8]

    def test_remainder_one_rebalanced(self):
        """The QT-02 case: 17 devs gave [8,8,1] and the lone dev vanished."""
        chunks = chunk_without_singletons(list(range(17)))
        assert [len(c) for c in chunks] == [8, 7, 2]

    def test_nine_items(self):
        chunks = chunk_without_singletons(list(range(9)))
        assert [len(c) for c in chunks] == [7, 2]

    def test_single_item_returned_whole(self):
        assert chunk_without_singletons([42]) == [[42]]

    @given(n=st.integers(min_value=2, max_value=200))
    @settings(max_examples=120, deadline=None)
    def test_property_no_singleton_and_union_preserved(self, n):
        items = list(range(n))
        chunks = chunk_without_singletons(items)
        flat = [x for c in chunks for x in c]
        assert flat == items                       # order + completeness
        assert all(len(c) <= MAX_CLUSTER_SIZE for c in chunks)
        assert all(len(c) >= 2 for c in chunks)    # QT-02: never a singleton


# ── #18 QT-03: partial rank-file reconciliation in merge ─────────────────────

class TestMergeReconciliation:
    def test_partial_rank_file_falls_back_missing_logins(self, tmp_path, monkeypatch, capsys):
        """A rank file with fewer logins than the cluster must not silently
        drop the missing devs from the normalized output (QT-03)."""
        import sys as _sys
        import merge_normalized
        tmp = str(tmp_path)
        (tmp_path / "triage-T.json").write_text(json.dumps({
            "clusters": [{"id": 0, "logins": ["a", "b", "c"], "scoreRange": [60, 70]}],
            "isolated": [],
        }))
        # Ranker returned only 2 of 3 logins
        (tmp_path / "rank-T-cluster-0.json").write_text(json.dumps({
            "clusterId": 0,
            "rankings": [
                {"login": "a", "normalizedScore": 71},
                {"login": "b", "normalizedScore": 64},
            ],
        }))
        (tmp_path / "score-T-batch-0.json").write_text(json.dumps({
            "scores": [{"login": "a", "score": 70}, {"login": "b", "score": 65},
                        {"login": "c", "score": 61}],
        }))
        monkeypatch.setattr(merge_normalized, "OUTPUT_DIR", tmp)
        monkeypatch.setattr(_sys, "argv", ["merge_normalized.py", "T"])
        merge_normalized.main()
        out = json.loads((tmp_path / "normalized-T.json").read_text())
        by_login = {e["login"]: e for e in out}
        assert set(by_login) == {"a", "b", "c"}
        assert by_login["c"]["normalizedScore"] == 61  # raw-score fallback
        assert by_login["c"]["rankingMethod"] == "ai_cluster_fallback"
        assert "partial" in capsys.readouterr().out


# ── #19 QT-10: score filter before trim ──────────────────────────────────────

class TestFilterBeforeTrim:
    def test_score_zero_devs_do_not_burn_slots(self):
        """A score-0 dev with a high composite must not occupy a paid slot."""
        profiles = [{"login": l} for l in ("zero", "good1", "good2")]
        score_map = {
            "zero": {"score": 0},
            "good1": {"score": 70},
            "good2": {"score": 60},
        }
        kept, skipped = filter_pushable_profiles(profiles, score_map)
        assert skipped == 1
        scored = [{"profile": p, "compositeScore": {"good1": 50, "good2": 40}.get(p["login"], 99)}
                  for p in kept]
        trimmed = trim_to_max_results(scored, 2)
        logins = {t["profile"]["login"] for t in trimmed}
        assert logins == {"good1", "good2"}  # both slots go to scored devs

    def test_non_numeric_and_missing_scores_filtered(self):
        profiles = [{"login": l} for l in ("a", "b", "c", "d")]
        score_map = {"a": {"score": "alto"}, "b": {"score": float("nan")}, "d": {"score": 5}}
        kept, skipped = filter_pushable_profiles(profiles, score_map)
        assert [p["login"] for p in kept] == ["d"]
        assert skipped == 3


