# ── #22 JD-06/MATH-11: robust pass2 trigger ──────────────────────────────────

class TestDecidePass2:
    def test_low_median_triggers(self):
        decision, _, median = decide_pass2([30, 40, 50, 45, 35], 1)
        assert decision == "pass2"
        assert median == 40

    def test_high_median_continues(self):
        assert decide_pass2([70, 80, 75], 1)[0] == "continue"

    def test_empty_sample_never_triggers(self):
        """MATH-11: avg([])=0 used to ALWAYS trigger a worldwide pass2."""
        decision, reason, _ = decide_pass2([], 1)
        assert decision == "continue"
        assert "insufficient" in reason

    def test_thin_sample_never_triggers(self):
        assert decide_pass2([10, 20], 1)[0] == "continue"

    def test_pass_cap(self):
        assert decide_pass2([10, 20, 30], 2)[0] == "continue"

    def test_dead_band_borderline_continues(self):
        # median 57 is in [55, 60) -> dead band, no flapping
        decision, reason, _ = decide_pass2([57, 57, 57], 1)
        assert decision == "continue"
        assert "dead band" in reason

    def test_median_resists_outlier(self):
        """One outlier moved the old mean across the binary threshold."""
        # 9 devs at 70 (good), one catastrophic 0: mean=63 -> old logic OK,
        # but mean with two zeros = 56 -> old logic triggered. Median: 70.
        assert decide_pass2([70] * 8 + [0, 0], 1)[0] == "continue"

    @given(values=st.lists(st.integers(min_value=0, max_value=100), min_size=0, max_size=10),
           pass_number=st.integers(min_value=1, max_value=3))
    @settings(max_examples=200, deadline=None)
    def test_property_trigger_iff_median_below_band(self, values, pass_number):
        import statistics
        decision, _, _ = decide_pass2(values, pass_number)
        if pass_number >= 2 or len(values) < MIN_MC_SAMPLES:
            assert decision == "continue"
        else:
            expected = "pass2" if statistics.median(values) < PASS2_THRESHOLD - PASS2_DEAD_BAND else "continue"
            assert decision == expected


# ── #20 JD-05: JD-dominant weight profile ────────────────────────────────────

class TestSelectWeights:
    def test_jd_mode_uses_jd_weights(self):
        config = rank_config()
        selected = select_weights(config, "jd")
        assert selected["weights"] == config["jd_weights"]
        assert selected["weights"]["codeQuality"] == 0.50  # JD score dominates

    def test_manual_mode_keeps_base_weights(self):
        config = rank_config()
        selected = select_weights(config, "manual")
        assert selected["weights"] == config["weights"]

    def test_config_without_jd_profile_falls_back(self):
        config = {"weights": {"codeQuality": 0.2}, "max_prefilter_boost": 56}
        assert select_weights(config, "jd")["weights"] == config["weights"]

    def test_both_profiles_sum_to_one(self):
        config = rank_config()
        for profile in ("weights", "jd_weights"):
            assert abs(sum(config[profile].values()) - 1.0) < 1e-9, profile

    # The forensic counterexample (jd 75 vs jd 35 with maxed social metrics):
    # full dominance would need a jd weight > 0.71 — beyond the agreed 0.50.
    # What 0.50 guarantees, pinned below: (a) with comparable social profiles
    # the jd score decides the order; (b) the social-star advantage SHRINKS
    # sharply vs the old 0.20 profile. Validated on 3 real tasks (top-10
    # turnover replaced jd 27-33 with jd 51-87).

    _SOCIAL_STAR_PF = {"languageFitPct": 100.0, "lifetimePRs": 200, "mergeRate": 1.0,
                       "prefilterBoost": 56}
    _SOCIAL_STAR_GQL = {"totalPullRequestReviewContributions": 100,
                        "repositoriesContributedTo": ["a"] * 10,
                        "commitsPerRepo": [{"totalCount": 500}], "totalStarsReceived": 5000,
                        "releasesByRepo": [{"count": 20}], "watchersByRepo": [{"count": 100}]}

    def test_jd_score_decides_between_comparable_profiles(self):
        from deterministic_rank import compute_deterministic_rank
        config = select_weights(rank_config(), "jd")
        pf = {"languageFitPct": 60.0, "lifetimePRs": 40, "mergeRate": 0.5, "prefilterBoost": 20}
        gql = {"repositoriesContributedTo": ["a", "b"]}
        fit75 = compute_deterministic_rank(pf, gql, 75, config)
        fit35 = compute_deterministic_rank(pf, gql, 35, config)
        assert fit75["deterministicRank"] - fit35["deterministicRank"] == 20.0  # 0.50 * 40

    def test_social_star_advantage_shrinks_vs_old_weights(self):
        from deterministic_rank import compute_deterministic_rank
        base = rank_config()
        weak_pf = {"languageFitPct": 40.0, "lifetimePRs": 0, "mergeRate": 0.0, "prefilterBoost": 0}

        def margin(config):
            star = compute_deterministic_rank(self._SOCIAL_STAR_PF, self._SOCIAL_STAR_GQL, 35, config)
            fit = compute_deterministic_rank(weak_pf, {}, 75, config)
            return star["deterministicRank"] - fit["deterministicRank"]

        old_margin = margin(base)                          # 0.20 profile
        new_margin = margin(select_weights(base, "jd"))    # 0.50 profile
        assert new_margin < old_margin / 2, (old_margin, new_margin)


