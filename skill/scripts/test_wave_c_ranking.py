# ── #23a QT-12: gate scanError passthrough ───────────────────────────────────

class TestGatePassthrough:
    def test_scan_error_dev_is_unconditionally_scorable(self):
        config = load_config()
        prefilter_map = {
            "broken": {"login": "broken", "languageFitPct": 0.0, "prefilterBoost": 0},
            "solid": {"login": "solid", "languageFitPct": 80.0, "prefilterBoost": 20},
        }
        graphql_map = {"broken": {"scanError": "GraphQL timeout"}, "solid": {}}
        passthrough, ceilings = partition_survivors(prefilter_map, graphql_map, config)
        assert [p["login"] for p in passthrough] == ["broken"]
        assert passthrough[0]["scanErrorPassthrough"] is True
        assert [c["login"] for c in ceilings] == ["solid"]

    def test_discard_rule_override_also_passes(self):
        config = load_config()
        prefilter_map = {"rescued": {"login": "rescued", "discardRuleOverride": True}}
        passthrough, ceilings = partition_survivors(prefilter_map, {}, config)
        assert len(passthrough) == 1 and not ceilings
